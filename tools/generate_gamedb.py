#!/usr/bin/env python3
"""Generate full-ROM identity and early loading-layout decoders from checked MRAs."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    games=json.loads((ROOT/'gamedb/games.json').read_text())
    for key in ('crc32','prefix_crc32'):assert len({g[key] for g in games})==len(games)
    params=',\n'.join(f"    parameter [31:0] {g['key'].upper()}_CRC32 = 32'h{g['crc32']}" for g in games)
    text='// Generated by tools/generate_gamedb.py; edit gamedb/games.json instead.\nmodule gb_mcr_game #(\n    parameter PREFIX = 0,\n'+params+'''
) (
    input wire [31:0] crc,
    output reg known, portrait, sg,
    output wire mcr2,
    output reg [1:0] family,
    output reg [2:0] mode,
    output reg [7:0] dips,
    output reg [19:0] size
);
    assign mcr2 = family == 1;
    always @* begin
        known=1; family=2; portrait=0; sg=0; mode=0; dips=8'hff; size=20'h3a000;
        case (crc)
'''
    for g in games:
        text+=f"            (PREFIX ? 32'h{g['prefix_crc32']} : {g['key'].upper()}_CRC32): begin family=2'd{g['family_id']}; mode=3'd{g['mod']}; portrait=1'b{int(g['portrait'])}; sg=1'b{int(g['sg'])}; dips=8'h{g['dips']:02x}; size=20'h{g['size']:05x}; end\n"
    text+='''            default: known=0;
        endcase
    end
endmodule
'''
    table='# Generated from games.json by tools/generate_gamedb.py.\n# crc32\tfamily\tmod\tDIP defaults\tname\tMRA MD5\n'
    table+=''.join(f"{g['crc32']}\tMCR{g['family']}\t{g['mod']}\t{g['dips']:02X} 00\t{g['name']}\t{g['md5']}\n" for g in games)
    for target,output in ((ROOT/'rtl/gamebub/gb_mcr_game.sv',text),(ROOT/'gamedb/games.tsv',table)):
        if args.check:
            if not target.exists() or target.read_text()!=output:raise SystemExit('Game catalog is stale; run tools/generate_gamedb.py')
        else:target.write_text(output)
    print(f'{"Verified" if args.check else "Generated"} {len(games)} game identities')
if __name__=='__main__':main()
